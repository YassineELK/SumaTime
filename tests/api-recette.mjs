async function call(user, payload, path = '/api/time', expected = 200, origin = base) {
  const headers = user ? { 'oai-authenticated-user-id': user[0], 'oai-authenticated-user-email': user[1] } : {};
  if (payload) Object.assign(headers, { Origin: origin, 'Content-Type': 'application/json' });
  const res = await fetch(base + path, { method: payload ? 'POST' : 'GET', headers, body: payload ? JSON.stringify(payload) : undefined });
  const result = res.headers.get('content-type')?.includes('text/csv') ? await res.text() : await res.json();
  assert.equal(res.status, expected, `${payload?.action || path}: ${JSON.stringify(result)}`); checks++;
  return result;
}
